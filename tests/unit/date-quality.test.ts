import { describe, expect, it } from 'vitest'
import { normalizeDate } from '@/page/extract/text'

describe('publication date quality', () => {
  it.each([
    '2026-02-31',
    '2026-04-31 01:00',
    '2025年2月29日',
    '1900-02-29',
    '2026-00-05',
    '2026-13-05',
    '2026-03-00',
    '2026-03-05T24:00:00Z',
    '2026-03-05T08:60:00Z',
    '2026-03-05T08:30:60+08:00',
    '2026-02-31T08:30:00+08:00',
    '2026-03-05T08:30:00+24:00',
    '2026-03-05T08:30:00+08:60',
    'Thu, 31 Feb 2026 08:30:00 GMT',
    'April 31, 2026 08:30:00 GMT',
    'Thu, 05 Mar 2026 24:00:00 GMT',
    '2',
    '123',
    '2026',
    '2026-03',
    'March 2026',
  ])('rejects invalid or incomplete source date %s', (raw) => {
    expect(normalizeDate(raw)).toBe('')
  })

  it.each([
    ['2024-02-29', '', '2024-02-29T00:00:00.000Z'],
    ['2000年2月29日', '', '2000-02-28T16:00:00.000Z'],
    ['2026-03-05T08:30:00+08:00', 'zh-CN', '2026-03-05T00:30:00.000Z'],
    ['2026-03-05T08:30:00-0500', '', '2026-03-05T13:30:00.000Z'],
    ['2026-03-05T08:30Z', 'zh-CN', '2026-03-05T08:30:00.000Z'],
    ['2026-03-05T08:30:00.123456Z', '', '2026-03-05T08:30:00.123Z'],
    ['2026-03-05 08:30:00.123', 'zh-CN', '2026-03-05T00:30:00.123Z'],
    ['2026年3月5日 12时30分15秒', '', '2026-03-05T04:30:15.000Z'],
    ['Thu, 05 Mar 2026 08:30:00 GMT', '', '2026-03-05T08:30:00.000Z'],
    ['Thu, 05 Mar 2026 08:30:00 +0800', '', '2026-03-05T00:30:00.000Z'],
    ['March 5, 2026 08:30:00 GMT', '', '2026-03-05T08:30:00.000Z'],
    ['1772668800', '', '2026-03-05T00:00:00.000Z'],
    ['1772668800000', '', '2026-03-05T00:00:00.000Z'],
  ])('preserves supported complete date %s', (raw, language, expected) => {
    expect(normalizeDate(raw, language)).toBe(expected)
  })
})
